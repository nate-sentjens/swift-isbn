  static func decompose(
    _ digits: String
  ) -> (prefix: String, name: String, registrant: String, publication: String)? {
    let gs1Prefix = String(digits.prefix(3))
    let body = digits.dropFirst(3).dropLast()

    for groupLength in 1...5 {
      guard groupLength <= body.count else { break }

      let groupDigits = String(body.prefix(groupLength))
      let key = gs1Prefix + "-" + groupDigits

      guard let groupData = groups[key] else { continue }

      let afterGroup = body.dropFirst(groupLength)
      let padded = String(afterGroup) + String(repeating: "0", count: max(0, 7 - afterGroup.count))

      guard let bodyValue = Int(String(padded.prefix(7))) else { return nil }

      for (range, registrantLength) in groupData.rules {
        if range.contains(bodyValue), registrantLength > 0 {
          let registrant = String(afterGroup.prefix(registrantLength))
          let publication = String(afterGroup.dropFirst(registrantLength))

          return (key, groupData.name, registrant, publication)
        }
      }

      return nil
    }

    return nil
  }

  static func lookupGroup(_ digits: String) -> (prefix: String, name: String)? {
    let gs1Prefix = String(digits.prefix(3))
    let body = digits.dropFirst(3).dropLast()

    for groupLength in 1...5 {
      guard groupLength <= body.count else { break }

      let groupDigits = String(body.prefix(groupLength))
      let key = gs1Prefix + "-" + groupDigits

      guard let groupData = groups[key] else { continue }

      return (key, groupData.name)
    }

    return nil
  }

